"""End-to-end encrypted chat of remote appointments.

A **remote appointment** has one conversation between the **patient** (the
customer's client logins) and the **appointment's professional** (its
logins). Nobody else takes part — the staff has no access, by construction:
the server never holds a key that opens the messages.

How the encryption works (the browser does all of it):

* every user has an **identity key pair** (ECDH P-256) generated in its
  browser; the private key is non-extractable and stays in the device's
  IndexedDB, the public key is published here (``User.chat_public_key``,
  JWK) with its **fingerprint** (SHA-256 of the uncompressed point);
* every conversation has a random **conversation key** (AES-256-GCM)
  generated by the participant who opens the chat first and **wrapped** for
  each participant's public key: an ephemeral ECDH key agreement, HKDF, and
  AES-GCM over the raw key (``ConversationKey``). A participant whose
  identity key changed (another device, a reset) gets a new envelope from
  the other party the next time that party opens the chat — the server only
  says who is missing one;
* messages are AES-GCM ciphertext of a JSON payload (the text and the
  attachments' names, types, sizes and IVs); attachments are AES-GCM blobs
  uploaded before the message that references them. The server sees sender,
  time, sizes and blob ids — never names, types or content; so the only
  type/size rules it can enforce are sizes and counts;
* both parties see a **safety code** (hash of both public keys) to compare
  over the video call: equal codes mean nobody swapped a key in transit.

Rules: the chat exists only for remote appointments; it is **open** while
the appointment is not cancelled and until ``OPEN_DAYS_AFTER`` days after
the visit (follow-up questions), read-only afterwards. New-message
notifications (no content) are throttled per side. Attachments follow the
documentation retention (purged with the prescriptions, see
``purge_expired``); orphan blobs (uploaded, never sent) go after a day.
"""

import base64
import hashlib
import json
import os
import secrets
from datetime import date, datetime, timedelta
from pathlib import Path

from sqlalchemy.orm import Session

from . import clock
from .auth import is_client, is_professional
from .models import Appointment, ChatAttachment, Conversation, User

OPEN_DAYS_AFTER = 30
MAX_MESSAGE_BYTES = 64 * 1024  # ciphertext, base64
MAX_ATTACHMENT_BYTES = int(os.getenv("CHAT_ATTACHMENT_MAX_BYTES", str(10 * 1024 * 1024)))
MAX_ATTACHMENTS_PER_MESSAGE = 5
MAX_ORPHANS = 20  # blobs uploaded and not yet sent, per user and conversation
ORPHAN_TTL = timedelta(days=1)
NOTIFY_INTERVAL = timedelta(minutes=30)
STORAGE_DIR = Path(os.getenv("CHAT_ATTACHMENTS_DIR", "./chat-attachments"))
CURVE = "P-256"


class ChatError(Exception):
    def __init__(self, message: str, status_code: int = 400):
        super().__init__(message)
        self.message = message
        self.status_code = status_code


# --- identity keys ---------------------------------------------------------------------


def _b64url_decode(text: str) -> bytes:
    padding = "=" * (-len(text) % 4)
    return base64.urlsafe_b64decode(text + padding)


def fingerprint_of(public_key_jwk: dict) -> str:
    """SHA-256 (hex) of the uncompressed EC point 04||x||y: the same value
    the browser computes, so both sides name a key the same way."""
    try:
        if public_key_jwk.get("kty") != "EC" or public_key_jwk.get("crv") != CURVE:
            raise ValueError
        x, y = _b64url_decode(public_key_jwk["x"]), _b64url_decode(public_key_jwk["y"])
        if len(x) != 32 or len(y) != 32:
            raise ValueError
    except (KeyError, TypeError, ValueError, AttributeError) as exc:
        raise ChatError("The public key must be an ECDH P-256 key in JWK form") from exc
    return hashlib.sha256(b"\x04" + x + y).hexdigest()


def public_jwk(text: str | None) -> dict | None:
    if not text:
        return None
    try:
        return json.loads(text)
    except ValueError:
        return None


def safety_code(fingerprints: list[str]) -> str:
    """60 decimal digits (12 groups of 5) from the sorted fingerprints of the
    two parties — compared out of band, like a safety number."""
    digest = hashlib.sha256("|".join(sorted(fingerprints)).encode()).digest()
    number = int.from_bytes(digest, "big")
    digits = str(number).rjust(60, "0")[:60]
    return " ".join(digits[i : i + 5] for i in range(0, 60, 5))


# --- participants and state ------------------------------------------------------------------


def is_participant(user: User, row: Appointment) -> bool:
    if is_professional(user):
        return user.professional_id == row.professional_id
    if is_client(user):
        return user.customer_id == row.customer_id
    return False


def side_of(user: User) -> str:
    return "professional" if is_professional(user) else "customer"


def participants(db: Session, row: Appointment) -> list[User]:
    """Every login that takes part: the customer's client users and the professional's users."""
    return (
        db.query(User)
        .filter(
            ((User.role == "client") & (User.customer_id == row.customer_id))
            | ((User.role == "professional") & (User.professional_id == row.professional_id))
        )
        .order_by(User.role, User.id)
        .all()
    )


def assert_chat_available(row: Appointment) -> None:
    if not row.remote:
        raise ChatError("The chat is available for remote appointments only", 409)


def open_until(row: Appointment) -> datetime:
    return row.marked_at + timedelta(days=OPEN_DAYS_AFTER)


def chat_state(row: Appointment, now: datetime | None = None) -> tuple[bool, str]:
    """(open, reason)."""
    now = now or clock.now()
    if row.status == "cancelada":
        return False, "The appointment was cancelled"
    if now > open_until(row):
        return False, f"The chat closed {OPEN_DAYS_AFTER} days after the visit"
    return True, ""


def get_or_create_conversation(db: Session, row: Appointment) -> Conversation:
    conversation = db.query(Conversation).filter(Conversation.appointment_id == row.id).first()
    if conversation is None:
        conversation = Conversation(appointment_id=row.id)
        db.add(conversation)
        db.flush()
    return conversation


# --- storage -------------------------------------------------------------------------------


def store_blob(content: bytes) -> str:
    STORAGE_DIR.mkdir(parents=True, exist_ok=True)
    key = f"{secrets.token_urlsafe(24)}.bin"
    (STORAGE_DIR / key).write_bytes(content)
    return key


def read_blob(key: str) -> bytes | None:
    path = STORAGE_DIR / key
    return path.read_bytes() if path.is_file() else None


def remove_blob(key: str) -> None:
    try:
        (STORAGE_DIR / key).unlink()
    except FileNotFoundError:
        pass


def delete_attachment(db: Session, attachment: ChatAttachment) -> None:
    remove_blob(attachment.storage_key)
    db.delete(attachment)


def purge_conversation_attachments(db: Session, conversation: Conversation) -> int:
    """Remove the encrypted blobs of a conversation (the messages stay, with
    their ciphertext; the attachments inside them become unavailable)."""
    rows = list(conversation.attachments)
    for attachment in rows:
        remove_blob(attachment.storage_key)
    conversation.attachments.clear()
    db.flush()
    return len(rows)


def delete_conversation(db: Session, row: Appointment) -> None:
    """The chat goes with a hard-deleted appointment: blobs and rows."""
    conversation = db.query(Conversation).filter(Conversation.appointment_id == row.id).first()
    if conversation is None:
        return
    for attachment in conversation.attachments:
        remove_blob(attachment.storage_key)
    db.delete(conversation)
    db.flush()


def purge_expired(db: Session, today: date | None = None, retain_until=None) -> dict:
    """Worker pass: attachments of visits past the documentation retention
    (``retain_until`` is app.prescriptions.retain_until) and orphan blobs
    older than a day."""
    today = today or clock.today()
    expired = 0
    if retain_until is not None:
        for conversation in db.query(Conversation).join(Appointment, Appointment.id == Conversation.appointment_id).all():
            if conversation.attachments and retain_until(conversation.appointment.marked_at) < today:
                expired += purge_conversation_attachments(db, conversation)
    stale = datetime.combine(today, datetime.min.time()) - ORPHAN_TTL
    orphans = db.query(ChatAttachment).filter(ChatAttachment.message_id.is_(None), ChatAttachment.created_at < stale).all()
    for attachment in orphans:
        delete_attachment(db, attachment)
    db.commit()
    return {"expired": expired, "orphans": len(orphans)}
